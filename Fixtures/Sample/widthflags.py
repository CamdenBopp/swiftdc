# Generates Fixtures/Sample/widthflags.s: constant probes of 32-bit flag
# setters, conditional selects and shifts over 64-bit register contents.
values = [0x0, 0x1, 0x7fffffff, 0x80000000, 0xffffffff, 0x100000001, 0xdeadbeef80000000, 0xffffffffffffffff]
pairs = [(a, b) for a in values for b in values if (values.index(a) + values.index(b)) % 3 == 0]
codes = ["eq", "ne", "hs", "lo", "mi", "pl", "vs", "vc", "hi", "ls", "ge", "lt", "gt", "le"]
out = ["// Generated by widthflags.py (python3 widthflags.py > widthflags.s); see WidthFlagOracleTests.",
       "// Each _wf_N returns a constant computed by 32-bit flag setters and",
       "// selects over 64-bit register contents. The test runs every function",
       "// natively and compares the tracer's recovered return value.",
       ".text", ".p2align 2",
       ".macro load reg, value",
       "    movz \\reg, #((\\value) & 0xffff)",
       "    movk \\reg, #(((\\value) >> 16) & 0xffff), lsl #16",
       "    movk \\reg, #(((\\value) >> 32) & 0xffff), lsl #32",
       "    movk \\reg, #(((\\value) >> 48) & 0xffff), lsl #48",
       ".endm"]
n = 0
def probe(body):
    global n
    out.append(f".globl _wf_{n}")
    out.append(f"_wf_{n}:")
    out.extend("    " + line for line in body)
    out.append("    ret")
    n += 1
for a, b in pairs:
    for op in ["cmp", "cmn", "tst"]:
        for cc in codes:
            probe([f"load x8, {a:#x}", f"load x9, {b:#x}", f"{op} w8, w9", f"cset x0, {cc}"])
for a, b in pairs:
    for sel in ["csel", "csinc", "csinv", "csneg"]:
        for cc in ["eq", "lo", "ge"]:
            probe([f"load x8, {a:#x}", f"load x9, {b:#x}", f"load x10, 0x10000000b", "cmp w8, w9",
                   f"{sel} w0, w10, w9, {cc}"])
for a in values:
    for shift in [1, 31]:
        probe([f"load x8, {a:#x}", f"asr w0, w8, #{shift}"])
    probe([f"load x8, {a:#x}", "add w0, w8, #1"])
    # A W operand extended into a 64-bit result: its low word, zero- or
    # sign-extended, never the X register's upper half.
    probe([f"load x8, {a:#x}", "load x9, 0x1000", "add x0, x9, w8, uxtw"])
    probe([f"load x8, {a:#x}", "load x9, 0x1000", "add x0, x9, w8, sxtw"])
print("\n".join(out))
