// Generate the deterministic 32-bit flag/select/shift probes on stdout.
let values: [UInt64] = [0, 1, 0x7fffffff, 0x80000000, 0xffffffff, 0x100000001, 0xdeadbeef80000000, .max]
let pairs = values.enumerated().flatMap { i, a in
    values.enumerated().compactMap { j, b in (i + j) % 3 == 0 ? (a, b) : nil }
}
let codes = ["eq", "ne", "hs", "lo", "mi", "pl", "vs", "vc", "hi", "ls", "ge", "lt", "gt", "le"]
var out = ["// Generated by widthflags.swift (swift widthflags.swift > widthflags.s); see WidthFlagOracleTests.",
           "// Each _wf_N returns a constant computed by 32-bit flag setters and",
           "// selects over 64-bit register contents. The test runs every function",
           "// natively and compares the tracer's recovered return value.",
           ".text", ".p2align 2", ".macro load reg, value",
           #"    movz \reg, #((\value) & 0xffff)"#,
           #"    movk \reg, #(((\value) >> 16) & 0xffff), lsl #16"#,
           #"    movk \reg, #(((\value) >> 32) & 0xffff), lsl #32"#,
           #"    movk \reg, #(((\value) >> 48) & 0xffff), lsl #48"#, ".endm"]
var count = 0
func hex(_ n: UInt64) -> String { "0x" + String(n, radix: 16) }
func probe(_ body: [String]) {
    out += [".globl _wf_\(count)", "_wf_\(count):"] + body.map { "    " + $0 } + ["    ret"]
    count += 1
}
for (a, b) in pairs {
    for op in ["cmp", "cmn", "tst"] {
        for cc in codes { probe(["load x8, \(hex(a))", "load x9, \(hex(b))", "\(op) w8, w9", "cset x0, \(cc)"]) }
    }
}
for (a, b) in pairs {
    for sel in ["csel", "csinc", "csinv", "csneg"] {
        for cc in ["eq", "lo", "ge"] {
            probe(["load x8, \(hex(a))", "load x9, \(hex(b))", "load x10, 0x10000000b", "cmp w8, w9", "\(sel) w0, w10, w9, \(cc)"])
        }
    }
}
for a in values {
    for shift in [1, 31] { probe(["load x8, \(hex(a))", "asr w0, w8, #\(shift)"]) }
    probe(["load x8, \(hex(a))", "add w0, w8, #1"])
    probe(["load x8, \(hex(a))", "load x9, 0x1000", "add x0, x9, w8, uxtw"])
    probe(["load x8, \(hex(a))", "load x9, 0x1000", "add x0, x9, w8, sxtw"])
}
print(out.joined(separator: "\n"))
