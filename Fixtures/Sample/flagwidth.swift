// Generate the symbolic flag-condition probes on stdout. FlagWidthOracleTests
// runs each one natively and evaluates what the tracer recovered.
let codes = ["eq", "ne", "hs", "lo", "mi", "pl", "vs", "vc", "hi", "ls", "ge", "lt", "gt", "le"]
var out = ["// Generated by flagwidth.swift (swift flagwidth.swift > flagwidth.s); see FlagWidthOracleTests.",
           "// Every compare, sum and test the tracer models, at both widths, with each form of",
           "// second operand, under every condition code. A _cset function returns the",
           "// condition as 0 or 1; a _b function branches on it and returns 1 when taken.",
           "// The arguments arrive in x0 and x1.",
           ".text", ".p2align 2"]
var count = 0
func probe(_ prefix: String, _ name: String, _ setter: [String], _ code: String, branch: Bool) {
    let symbol = "_\(prefix)_\(count)_\(code)_\(name)"
    out += [".globl \(symbol)_cset", "\(symbol)_cset:"] + setter.map { "    " + $0 }
    out += ["    cset x0, \(code)", "    ret"]
    if branch {
        out += [".globl \(symbol)_b", "\(symbol)_b:"] + setter.map { "    " + $0 }
        out += ["    b.\(code) 1f", "    mov x0, #0", "    ret", "1:", "    mov x0, #1", "    ret"]
    }
    count += 1
}
for r in ["w", "x"] {
    // A shift or an extend widens the operand past the word a 32-bit compare
    // reads: `cmp w0, w1, lsl #4` compares the low word of `w1 << 4`.
    var second = ["\(r)1", "\(r)1, lsl #4", "\(r)1, lsl #28", "\(r)1, lsr #3", "\(r)1, asr #3",
                  "w1, sxtb", "w1, sxth", "w1, uxtb", "w1, uxth", "w1, sxtb #2", "#5"]
    if r == "x" { second += ["w1, sxtw", "w1, uxtw"] }
    for operand in second {
        for code in codes {
            probe("fw", "cmp", ["cmp \(r)0, \(operand)"], code, branch: true)
            probe("fw", "cmn", ["cmn \(r)0, \(operand)"], code, branch: false)
            probe("fw", "subs", ["subs \(r)8, \(r)0, \(operand)"], code, branch: false)
            probe("fw", "adds", ["adds \(r)8, \(r)0, \(operand)"], code, branch: false)
        }
    }
}
// A test: N and Z from the result, C and V clear. A 32-bit result's sign is
// bit 31. A setter fed by a difference or a sum tests that value, and a
// conditional compare builds on the test's condition.
for r in ["w", "x"] {
    let second = ["\(r)1", "\(r)1, lsl #4", "\(r)1, lsr #3", "\(r)1, asr #3", "\(r)1, ror #7", "#0xff",
                  r == "w" ? "#0x80000000" : "#0x8000000000000000"]
    for operand in second {
        for code in codes {
            probe("ft", "tst", ["tst \(r)0, \(operand)"], code, branch: true)
            probe("ft", "ands", ["ands \(r)8, \(r)0, \(operand)"], code, branch: false)
        }
    }
    for code in codes {
        probe("ft", "foldsub", ["sub \(r)8, \(r)0, \(r)1", "mov \(r)9, #-1", "tst \(r)8, \(r)9"], code, branch: true)
        probe("ft", "foldadd", ["add \(r)8, \(r)0, \(r)1", "mov \(r)9, #-1", "ands \(r)9, \(r)8, \(r)9"], code, branch: true)
        for incoming in ["eq", "lt", "hs", "gt"] {
            probe("ft", "ccmp", ["tst \(r)0, \(r)1", "ccmp \(r)0, \(r)1, #4, \(incoming)"], code, branch: false)
        }
    }
}

// Selected NZCV producers retain their kind and setter width across a CFG
// diamond. Constant probes cover every code; symbolic CMP also feeds CCMP.
func diamond(_ taken: [String], _ fall: [String]) -> [String] {
    ["cbz x0, 8f"] + fall + ["b 9f", "8:"] + taken + ["9:"]
}
func constantSetter(_ kind: String, _ r: String, _ taken: Bool) -> [String] {
    let sign = r == "w" ? "0x80000000" : "0x8000000000000000"
    let max = r == "w" ? "0x7fffffff" : "0x7fffffffffffffff"
    switch kind {
    case "cmp": return ["mov \(r)8, #\(taken ? sign : "1")", "cmp \(r)8, #1"]
    case "cmn": return ["mov \(r)8, #\(taken ? max : "-1")", "cmn \(r)8, #1"]
    default: return ["mov \(r)8, #\(taken ? sign : "0")", "tst \(r)8, \(r)8"]
    }
}
var selectedFlags: [(String, [String], [String])] = []
for kind in ["cmp", "cmn", "tst"] {
    for r in ["w", "x"] {
        selectedFlags.append((kind + r, constantSetter(kind, r, true), constantSetter(kind, r, false)))
    }
}
// These payloads are identical across arms; only flagsWidth diverges.
for (kind, value, setter) in [("cmp", "0x80000000", "cmp"), ("cmn", "0xffffffff", "cmn"), ("tst", "0x80000000", "tst")] {
    let word = ["mov w8, #\(value)", kind == "tst" ? "tst w8, w8" : "\(setter) w8, #\(kind == "cmn" ? "1" : "0")"]
    let wide = ["mov x8, #\(value)", kind == "tst" ? "tst x8, x8" : "\(setter) x8, #\(kind == "cmn" ? "1" : "0")"]
    selectedFlags.append((kind + "width", word, wide))
}
selectedFlags.append(("pairedwidth", ["mov w8, #0x80000000", "cmp w8, #1"], ["mov w8, #0x80000001", "cmp x8, #1"]))
selectedFlags.append(("mixedkind", constantSetter("cmp", "w", true), constantSetter("tst", "x", true)))
for r in ["w", "x"] {
    selectedFlags.append(("symcmp" + r, ["cmp \(r)1, #1"], ["cmp \(r)1, #0"]))
}
func selectedFlagProbes(_ name: String, _ body: [String]) {
    for code in codes { probe("fm", name, body, code, branch: true) }
    for width in ["w", "x"] {
        for incoming in ["eq", "lt", "hs", "vs"] {
            for code in ["eq", "ne", "lt", "vs"] {
                probe("fm", name + "ccmp" + width + incoming,
                      body + ["ccmp \(width)1, #1, #4, \(incoming)"], code, branch: false)
            }
        }
    }
}
for (name, taken, fall) in selectedFlags { selectedFlagProbes(name, diamond(taken, fall)) }
// A three-way switch can also erase the common payload in meet().
selectedFlagProbes("switchwidth", [
    "cmp x0, #0", "b.eq 6f", "cmp x0, #1", "b.eq 7f",
    "mov w8, #0x80000000", "cmp w8, #0", "b 9f",
    "6:", "mov w8, #0x80000000", "cmp w8, #0", "b 9f",
    "7:", "mov w8, #0x80000000", "cmp x8, #0", "9:"
])
// Independent flag/width select predicates may decline; any claim must
// still agree with native. Pairing their arms positionally would be wrong.
probe("fm", "independent", [
    "cbz x0, 6f", "cbz x1, 7f", "mov w8, #0x80000001", "cmp x8, #0", "b 8f",
    "7:", "mov x8, #0x80000000", "cmp x8, #0", "8:", "b 9f",
    "6:", "cbz x1, 7f", "mov w8, #0x80000001", "cmp w8, #0", "b 8f",
    "7:", "mov w8, #0x80000000", "cmp w8, #0", "8:", "b 9f", "9:"
], "mi", branch: false)

// Query bounds are separate from the preexisting retained-state depth.
// A traversal may fold eight choices to 0, but must decline a ninth; an
// output can retain depth eight but must decline a new ninth parent.
func boundedProbe(_ name: String, _ body: [String]) {
    out += [".globl _fb_\(name)", "_fb_\(name):"] + body.map { "    " + $0 }
}
func switchFlags(_ count: Int, uniform: Bool) -> [String] {
    var body: [String] = []
    for n in 0..<count { body += ["cmp x0, #\(n)", "b.eq \(n + 1)f"] }
    let fallback = uniform ? 99 : count % 2
    body += ["mov x8, #\(fallback)", "cmp x8, #0", "b 0f"]
    for n in 0..<count {
        body += ["\(n + 1):", "mov x8, #\(uniform ? n + 1 : n % 2)", "cmp x8, #0", "b 0f"]
    }
    return body + ["0:", "cset x0, \(uniform ? "vs" : "eq")", "ret"]
}
boundedProbe("choice8", switchFlags(8, uniform: true))
boundedProbe("choice9", switchFlags(9, uniform: true))
boundedProbe("result7", switchFlags(7, uniform: false))
boundedProbe("result8", switchFlags(8, uniform: false))
for n in [6, 7] {
    let definitions = ["eor x8, x0, #1"] + Array(repeating: "eor x8, x8, #1", count: n - 1)
    boundedProbe("predicate\(n)", definitions + ["cbz x8, 8f", "mov x9, #0", "cmp x9, #0", "b 9f", "8:", "mov x9, #1", "cmp x9, #0", "9:", "cset x0, eq", "ret"])
}


// The function entry also has an implicit caller edge. Its unknown NZCV
// cannot be replaced by a choice over just the explicit loop backedges.
for kind in ["common", "different", "switch"] {
    let name = "fe_" + kind
    out += [".globl _\(name)", "_\(name):", "    cset x4, hs", "    str x4, [x2]",
            "    subs x1, x1, #1", "    cbz x1, 9f"]
    if kind == "switch" {
        out += ["    cmp x0, #0", "    b.eq 6f", "    cmp x0, #1", "    b.eq 7f",
                "    mov w8, #1", "    cmp w8, #0", "    b _\(name)",
                "6:", "    mov w8, #1", "    cmp w8, #0", "    b _\(name)",
                "7:", "    mov x8, #1", "    cmp x8, #0", "    b _\(name)"]
    } else {
        out += ["    cbz x0, 6f", "    mov x8, #1", "    cmp x8, #0", "    b _\(name)",
                "6:", "    mov w8, #\(kind == "common" ? "1" : "2")", "    cmp w8, #0", "    b _\(name)"]
    }
    out += ["9:", "    ldr x0, [x2]", "    ret", ".globl _\(name)_caller", "_\(name)_caller:",
            "    stp x29, x30, [sp, #-16]!", "    mov x29, sp", "    mov x5, #0", "    cmp x5, #1",
            "    bl _\(name)", "    ldp x29, x30, [sp], #16", "    ret"]
}
out += [".globl _fe_control", "_fe_control:", "    mov x8, #1", "    cmp x8, #0",
        "    cset x4, hs", "    str x4, [x2]", "    mov x0, x4", "    ret"]


// An unmodeled caller scratch word still reaches a test producer. Ordinary
// queries retain partial 14/16 choices; C/V remain known-clear. Selected CMP
// and TST arms exercise unknown Boolean data separately from proof failure.
func partialFlagProbe(_ name: String, _ body: [String]) {
    out += [".globl _fp_\(name)", "_fp_\(name):", "    stp x29, x30, [sp, #-16]!", "    mov x29, sp", "    sub sp, sp, #16"]
    out += body.map { "    " + $0 }
    out += ["    add sp, sp, #16", "    ldp x29, x30, [sp], #16", "    ret"]
}
let partialChoice = ["b.eq 6f", "mov w9, #16", "b 7f", "6:", "mov w9, #14", "7:", "mov x0, x9"]
let unknownTest = ["mov x0, sp", "bl _fp_source", "ldr w0, [sp]", "ands w8, w0, #0xff"]
partialFlagProbe("plain", unknownTest + partialChoice)
partialFlagProbe("known", ["tst w1, #0xff"] + partialChoice)
partialFlagProbe("symbolic", ["mov x0, x1", "bl _fp_identity", "tst w0, #0xff"] + partialChoice)
for kind in ["cmp", "test"] {
    let opaque = kind == "cmp" ? "cmp x0, #0" : "ands w8, w0, #0xff"
    let known = kind == "cmp" ? "cmp x1, #0" : "tst w1, #0xff"
    partialFlagProbe(kind, ["cbz x0, 3f", "mov x0, sp", "bl _fp_source", "ldr x0, [sp]", opaque,
                          "b 4f", "3:", known, "4:"] + partialChoice)
}
for code in ["hs", "lo", "vs", "vc"] {
    partialFlagProbe(code, unknownTest + ["cset x0, \(code)"])
}
out += [".globl _fp_source", "_fp_source:", "    str x1, [x0]", "    ret"]
out += [".globl _fp_identity", "_fp_identity:", "    ret"]

print(out.joined(separator: "\n"))
