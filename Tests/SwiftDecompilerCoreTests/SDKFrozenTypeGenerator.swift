import Foundation
import Testing
@testable import SwiftDecompilerCore

/// Regenerates `Sources/SwiftDecompilerCore/SDKFrozenTypes.swift` from the
/// SDK's module interfaces:
///
///     SWIFTDC_GENERATE_FROZEN=Sources/SwiftDecompilerCore/SDKFrozenTypes.swift \
///         swift test --filter generateSDKFrozenTypes
///
/// A system library is built for library evolution, so a struct or enum it
/// declares is resilient, address-only outside its module, unless it is
/// `@frozen` (or the older `@_fixed_layout`). A resilient value's `self`
/// travels by address in x20 (`ptr swiftself`): `Date.timeIntervalSince1970`
/// is `(ptr swiftself)`. A frozen loadable one travels as its words after the
/// formals, and x20 carries it only by address, for a mutating member.
@Test func generateSDKFrozenTypes() throws {
    guard let output = ProcessInfo.processInfo.environment["SWIFTDC_GENERATE_FROZEN"] else { return }
    let sdk = try #require(sdkRoot())
    let enumerator = try #require(FileManager.default.enumerator(atPath: sdk))
    var frozen = Set<String>()
    var mutating: [String: Set<String>] = [:]
    var interfaces = 0
    for case let path as String in enumerator where path.hasSuffix("arm64e-apple-macos.swiftinterface") {
        let components = path.split(separator: "/")
        guard let moduleDirectory = components.dropLast().last, moduleDirectory.hasSuffix(".swiftmodule"),
              let text = try? String(contentsOfFile: sdk + "/" + path, encoding: .utf8)
        else { continue }
        interfaces += 1
        let scan = FrozenTypeScanner.scan(text, module: String(moduleDirectory.dropLast(".swiftmodule".count)))
        frozen.formUnion(scan.frozen)
        mutating.merge(scan.mutating) { $0.union($1) }
    }
    let source = """
    // Generated by Tests/SwiftDecompilerCoreTests/SDKFrozenTypeGenerator.swift
    // from \(interfaces) arm64e-apple-macos module interfaces of the SDK at
    // \(sdk). Do not edit by hand.

    /// The structs and enums a system module declares `@frozen` (or
    /// `@_fixed_layout`), as their type names print, each with the names of
    /// the methods it or an extension of it declares `mutating`. Every
    /// other value type of a system library is resilient: its `self`
    /// travels by address in x20. A frozen one's travels as its words, in
    /// x20 only by address, for a mutating member.
    enum SDKFrozenTypes {
        static let mutatingMembers: [String: Set<String>] = {
            var table: [String: Set<String>] = [:]
            for line in data.split(separator: "\\n") {
                let fields = line.split(separator: " ", maxSplits: 1)
                guard let name = fields.first else { continue }
                table[String(name)] = Set((fields.dropFirst().first ?? "").split(separator: ",").map(String.init))
            }
            return table
        }()

        static var names: Dictionary<String, Set<String>>.Keys { mutatingMembers.keys }

        private static let data = \"\"\"
    \(frozen.sorted().map { name in
        let members = (mutating[name] ?? []).sorted().joined(separator: ",")
        return members.isEmpty ? name : name + " " + members
    }.joined(separator: "\n"))
    \"\"\"
    }

    """
    try source.write(toFile: output, atomically: true, encoding: .utf8)
    print("Frozen value types: \(frozen.count) from \(interfaces) interfaces, \(frozen.filter { mutating[$0] != nil }.count) with mutating members")
}

private func sdkRoot() -> String? {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
    process.arguments = ["--show-sdk-path"]
    let pipe = Pipe()
    process.standardOutput = pipe
    guard (try? process.run()) != nil else { return nil }
    process.waitUntilExit()
    let path = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        .trimmingCharacters(in: .whitespacesAndNewlines)
    return path.isEmpty ? nil : path
}

/// A scanner for the declarations of a `.swiftinterface`: enough of the
/// lexical structure to nest type and extension scopes, never a parser of
/// the code inside an `@inlinable` body.
enum FrozenTypeScanner {
    static func frozenValueTypes(in text: String, module: String) -> Set<String> {
        scan(text, module: module).frozen
    }

    /// The frozen value types, and the `mutating` methods each type or
    /// extension scope declares, by scope name.
    static func scan(_ text: String, module: String) -> (frozen: Set<String>, mutating: [String: Set<String>]) {
        let lines = keepingFirstConditionalBranch(text)
        let code = strippingLiteralsAndComments(lines.joined(separator: "\n"))
        var result = Set<String>()
        var mutating: [String: Set<String>] = [:]
        // One entry per open brace: the scope's qualified name, or nil for
        // a brace that opens no type or extension.
        var scopes: [String?] = []
        var pending = ""
        let mutatingFunction = try! NSRegularExpression(pattern: #"\bmutating\s+func\s+([A-Za-z_][A-Za-z0-9_]*|[^\s(<]+)"#)
        func noteMutating(in text: String) {
            guard let scope = scopes.last, let scope else { return }
            let ns = text as NSString
            for match in mutatingFunction.matches(in: text, range: NSRange(location: 0, length: ns.length)) {
                mutating[scope, default: []].insert(ns.substring(with: match.range(at: 1)))
            }
        }
        let declaration = try! NSRegularExpression(
            pattern: #"\b(struct|enum|class|actor|protocol|extension)\s+([A-Za-z_][A-Za-z0-9_.:]*)"#)
        for character in code {
            switch character {
            case "{":
                noteMutating(in: pending)
                var name: String?
                // The declaration the brace opens: the last line before it
                // that is not an attribute, with the attribute lines above.
                let text = pending as NSString
                if let match = declaration.matches(in: pending, range: NSRange(location: 0, length: text.length)).last {
                    let keyword = text.substring(with: match.range(at: 1))
                    let raw = text.substring(with: match.range(at: 2)).replacingOccurrences(of: "::", with: ".")
                    let outer = scopes.last.flatMap { $0 } ?? module
                    if keyword == "extension" {
                        name = raw.contains(".") ? raw : module + "." + raw
                    } else if scopes.allSatisfy({ $0 != nil }) {
                        name = outer + "." + raw
                        let head = text.substring(to: match.range.location)
                        let attributes = head.components(separatedBy: "\n").suffix(4).joined(separator: "\n")
                        if keyword == "struct" || keyword == "enum",
                           attributes.contains("@frozen") || attributes.contains("@_fixed_layout") {
                            result.insert(name!)
                        }
                    }
                }
                // A brace inside a function body opens no named scope, and
                // nothing nested inside one is a type the module exports.
                scopes.append(scopes.allSatisfy({ $0 != nil }) ? name : nil)
                pending = ""
            case "}":
                noteMutating(in: pending)
                if !scopes.isEmpty { scopes.removeLast() }
                pending = ""
            default:
                pending.append(character)
            }
        }
        return (result, mutating)
    }

    /// Keep only each `#if`'s first branch, so a declaration whose header
    /// differs by branch opens one brace, not two.
    static func keepingFirstConditionalBranch(_ text: String) -> [String] {
        var kept: [String] = []
        // Per open `#if`: whether its current branch is skipped.
        var skipping: [Bool] = []
        for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.hasPrefix("#if") {
                skipping.append(skipping.last ?? false)
                continue
            }
            if trimmed.hasPrefix("#elseif") || trimmed.hasPrefix("#else") {
                if !skipping.isEmpty { skipping[skipping.count - 1] = true }
                continue
            }
            if trimmed.hasPrefix("#endif") {
                if !skipping.isEmpty { skipping.removeLast() }
                continue
            }
            if skipping.last ?? false { continue }
            kept.append(String(line))
        }
        return kept
    }

    /// The code with comments, string and character literals blanked.
    static func strippingLiteralsAndComments(_ text: String) -> String {
        var out = ""
        let characters = Array(text)
        var index = 0
        while index < characters.count {
            let c = characters[index]
            let next = index + 1 < characters.count ? characters[index + 1] : "\0"
            if c == "/", next == "/" {
                while index < characters.count, characters[index] != "\n" { index += 1 }
                continue
            }
            if c == "/", next == "*" {
                index += 2
                var depth = 1
                while index < characters.count, depth > 0 {
                    if characters[index] == "/", index + 1 < characters.count, characters[index + 1] == "*" { depth += 1; index += 1 }
                    else if characters[index] == "*", index + 1 < characters.count, characters[index + 1] == "/" { depth -= 1; index += 1 }
                    index += 1
                }
                continue
            }
            if c == "\"" {
                let triple = index + 2 < characters.count && characters[index + 1] == "\"" && characters[index + 2] == "\""
                index += triple ? 3 : 1
                while index < characters.count {
                    if characters[index] == "\\" { index += 2; continue }
                    if triple {
                        if characters[index] == "\"", index + 2 < characters.count,
                           characters[index + 1] == "\"", characters[index + 2] == "\"" { index += 3; break }
                    } else if characters[index] == "\"" || characters[index] == "\n" {
                        index += 1; break
                    }
                    index += 1
                }
                out.append("\"\"")
                continue
            }
            out.append(c)
            index += 1
        }
        return out
    }
}

/// The scanner against the shapes the interfaces use.
@Test func theFrozenScannerNamesNestedFrozenValueTypes() {
    let text = """
    @usableFromInline
    @frozen internal struct _ArrayBuffer<Element> : Swift::_ArrayBufferProtocol {
      @inlinable internal func f() { let s = "}{"; _ = s }
    }
    public struct Resilient { public var x: Swift::Int }
    extension Swift::Unicode {
      @frozen public struct Scalar : Swift::Sendable {
        public enum Inner { case a }
        public mutating func bump()
        @inlinable public mutating func reset() { var x = 0; x += 1 }
        public func peek() -> Swift::Int
      }
    }
    #if compiler(>=5.3) && $Feature
    @frozen public enum Picked : Swift::Sendable {
    #else
    @frozen public enum Picked {
    #endif
      case one
    }
    // @frozen public struct Commented {
    @_fixed_layout public struct Old { }
    """
    let scan = FrozenTypeScanner.scan(text, module: "Swift")
    #expect(scan.frozen == ["Swift._ArrayBuffer", "Swift.Unicode.Scalar", "Swift.Picked", "Swift.Old"])
    #expect(scan.mutating == ["Swift.Unicode.Scalar": ["bump", "reset"]], "\(scan.mutating)")
}
