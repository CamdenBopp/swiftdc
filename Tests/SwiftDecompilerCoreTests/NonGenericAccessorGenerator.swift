import Demangling
import Foundation
import MachOKit
import Testing
@testable import SwiftDecompilerCore

/// Regenerates `Sources/SwiftDecompilerCore/NonGenericMetadataAccessors.swift`
/// from this host's dyld shared cache:
///
///     SWIFTDC_GENERATE_ACCESSORS=Sources/SwiftDecompilerCore/NonGenericMetadataAccessors.swift \
///         swift test --filter generateNonGenericMetadataAccessors
///
/// A type metadata accessor takes the metadata request, then one argument
/// per generic parameter (swift/lib/IRGen/MetadataRequest.cpp), so a
/// non-generic type's takes the request alone. A type is generic when its
/// nominal type descriptor (`…Mn`) has the generic bit, 0x80, in its flags
/// (swift/include/swift/ABI/MetadataValues.h:1940). The table names every
/// accessor the system's Swift libraries export for a non-generic type.
@Test func generateNonGenericMetadataAccessors() throws {
    guard let output = ProcessInfo.processInfo.environment["SWIFTDC_GENERATE_ACCESSORS"] else { return }
    let cache = try #require(FullDyldCache.host)
    let reader = CacheReader(full: cache)
    var names = Set<String>()
    var images = 0, generic = 0
    for image in cache.machOFiles()
    where image.imagePath.hasPrefix("/usr/lib/swift/") || image.imagePath.hasPrefix("/System/Library/Frameworks/") {
        guard let base = image.loadCommands.infos(of: LoadCommand.segment64)
            .first(where: { $0.segmentName == "__TEXT" }).map({ UInt64($0.vmaddr) })
        else { continue }
        var addresses: [String: UInt64] = [:]
        for export in image.exportedSymbols where export.name.hasPrefix("_$s") {
            guard let offset = export.offset, offset >= 0 else { continue }
            addresses[export.name] = base &+ UInt64(offset)
        }
        var found = false
        for (symbol, _) in addresses where symbol.hasSuffix("Ma") {
            guard let descriptor = addresses[String(symbol.dropLast(2)) + "Mn"],
                  let flags = reader.bytes(at: descriptor, count: 4), flags.count == 4
            else { continue }
            let raw = flags.withUnsafeBytes { $0.loadUnaligned(as: UInt32.self) }
            if raw & 0x80 != 0 { generic += 1; continue }
            guard let node = try? demangleAsNode(String(symbol.dropFirst())) else { continue }
            let printed = node.print(using: .default)
            let prefix = "type metadata accessor for "
            guard printed.hasPrefix(prefix) else { continue }
            names.insert(String(printed.dropFirst(prefix.count)))
            found = true
        }
        if found { images += 1 }
    }
    let version = ProcessInfo.processInfo.operatingSystemVersionString
    let source = """
    // Generated by Tests/SwiftDecompilerCoreTests/NonGenericAccessorGenerator.swift
    // from the Swift libraries of the macOS \(version) shared cache
    // \(cache.header.uuid.uuidString) (\(images) images). Do not edit by hand.

    /// The types whose metadata accessor a system Swift library exports and
    /// whose nominal type descriptor is not generic, as `type metadata
    /// accessor for <type>` names them: each accessor takes the metadata
    /// request alone.
    enum NonGenericMetadataAccessors {
        static let types: Set<String> = Set(data.split(separator: "\\n").map(String.init))

        private static let data = \"\"\"
    \(names.sorted().joined(separator: "\n"))
    \"\"\"
    }

    """
    try source.write(toFile: output, atomically: true, encoding: .utf8)
    print("Non-generic accessors: \(names.count) from \(images) images; \(generic) generic left out")
}
