import Demangling
import Foundation
import MachOKit
import Testing
@testable import SwiftDecompilerCore

/// Regenerates `Sources/SwiftDecompilerCore/SDKMetadataAccessors.swift` from
/// this host's dyld shared cache:
///
///     SWIFTDC_GENERATE_ACCESSORS=Sources/SwiftDecompilerCore/SDKMetadataAccessors.swift \
///         swift test --filter generateSDKMetadataAccessors
///
/// A type metadata accessor takes the metadata request, then the type's key
/// generic arguments, its parameters' metadata and the witness tables of
/// their conformance requirements (swift/lib/IRGen/MetadataRequest.cpp).
/// Up to three travel directly; past three, one pointer to a buffer of all
/// of them does (`NumDirectGenericTypeMetadataAccessFunctionArgs`). The
/// count is `NumKeyArguments` in the generic context header of the type's
/// nominal descriptor (`…Mn`), present when the flags' generic bit, 0x80,
/// is set (swift/include/swift/ABI/MetadataValues.h). The header follows
/// the kind's own fields (swift/include/swift/ABI/Metadata.h): five
/// common words, then two for a struct or an enum and six for a class;
/// after `InstantiationCache` and `DefaultInstantiationPattern` come
/// `NumParams`, `NumRequirements` and `NumKeyArguments`, 16 bits each.
@Test func generateSDKMetadataAccessors() throws {
    guard let output = ProcessInfo.processInfo.environment["SWIFTDC_GENERATE_ACCESSORS"] else { return }
    let cache = try #require(FullDyldCache.host)
    let reader = CacheReader(full: cache)
    var counts: [String: Int] = [:]
    var kinds: [String: Character] = [:]
    var conflicting = Set<String>()
    var images = 0, unreadable = 0
    for image in cache.machOFiles()
    where image.imagePath.hasPrefix("/usr/lib/swift/") || image.imagePath.hasPrefix("/System/Library/Frameworks/") {
        guard let base = image.loadCommands.infos(of: LoadCommand.segment64)
            .first(where: { $0.segmentName == "__TEXT" }).map({ UInt64($0.vmaddr) })
        else { continue }
        var addresses: [String: UInt64] = [:]
        for export in image.exportedSymbols where export.name.hasPrefix("_$s") {
            guard let offset = export.offset, offset >= 0 else { continue }
            addresses[export.name] = base &+ UInt64(offset)
        }
        var found = false
        for (symbol, _) in addresses where symbol.hasSuffix("Ma") {
            guard let descriptor = addresses[String(symbol.dropLast(2)) + "Mn"],
                  let flagBytes = reader.bytes(at: descriptor, count: 4), flagBytes.count == 4
            else { continue }
            let flags = flagBytes.withUnsafeBytes { $0.loadUnaligned(as: UInt32.self) }
            let kind: Character? = switch flags & 0x1f {
            case 16: "c"
            case 17: "s"
            case 18: "e"
            default: nil
            }
            let keyArguments: Int
            if flags & 0x80 == 0 {
                keyArguments = 0
            } else {
                let kindFields: UInt64 = switch flags & 0x1f {
                case 16: 24 // class
                case 17, 18: 8 // struct, enum
                default: 0
                }
                guard kindFields != 0,
                      let bytes = reader.bytes(at: descriptor &+ 20 &+ kindFields &+ 12, count: 2), bytes.count == 2
                else { unreadable += 1; continue }
                keyArguments = Int(bytes.withUnsafeBytes { $0.loadUnaligned(as: UInt16.self) })
            }
            guard let node = try? demangleAsNode(String(symbol.dropFirst())) else { continue }
            let printed = node.print(using: .default)
            let prefix = "type metadata accessor for "
            guard printed.hasPrefix(prefix) else { continue }
            let name = String(printed.dropFirst(prefix.count))
            // Two libraries printing one name with different counts prove
            // neither.
            if let known = counts[name], known != keyArguments || kinds[name] != kind { conflicting.insert(name) }
            counts[name] = keyArguments
            kinds[name] = kind
            found = true
        }
        if found { images += 1 }
    }
    for name in conflicting { counts[name] = nil }
    let version = ProcessInfo.processInfo.operatingSystemVersionString
    let lines = counts.keys.sorted().map { "\($0) \(counts[$0]!) \(kinds[$0].map(String.init) ?? "-")" }
    let source = """
    // Generated by Tests/SwiftDecompilerCoreTests/MetadataAccessorGenerator.swift
    // from the Swift libraries of the macOS \(version) shared cache
    // \(cache.header.uuid.uuidString) (\(images) images). Do not edit by hand.

    /// The types whose metadata accessor a system Swift library exports, as
    /// `type metadata accessor for <type>` names them, with the number of
    /// key generic arguments each accessor takes after the metadata request
    /// (0 for a non-generic type) and the descriptor's kind: `c` class, `s`
    /// struct, `e` enum, `-` another. A name two libraries disagree on is
    /// left out.
    enum SDKMetadataAccessors {
        struct Entry: Sendable, Equatable {
            let keyArguments: Int
            let kind: Character
        }

        static let types: [String: Entry] = {
            var table: [String: Entry] = [:]
            for line in data.split(separator: "\\n") {
                let fields = line.split(separator: " ")
                guard fields.count >= 3, let count = Int(fields[fields.count - 2]), let kind = fields.last?.first
                else { continue }
                table[fields.dropLast(2).joined(separator: " ")] = Entry(keyArguments: count, kind: kind)
            }
            return table
        }()

        static let keyArguments: [String: Int] = types.mapValues(\\.keyArguments)

        private static let data = \"\"\"
    \(lines.joined(separator: "\n"))
    \"\"\"
    }

    """
    try source.write(toFile: output, atomically: true, encoding: .utf8)
    print("Metadata accessors: \(counts.count) from \(images) images; \(conflicting.count) conflicting, \(unreadable) unreadable")
}
