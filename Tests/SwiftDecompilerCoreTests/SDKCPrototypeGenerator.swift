import Foundation
import Testing
@testable import SwiftDecompilerCore

/// Regenerates `Sources/SwiftDecompilerCore/SDKCPrototypes.swift` from this
/// host's macOS SDK:
///
///     SWIFTDC_GENERATE_SDK_C_PROTOTYPES=Sources/SwiftDecompilerCore/SDKCPrototypes.swift \
///         swift test --filter generateSDKCPrototypes
///
/// A call to a C function has no signature in the binary, so its arguments
/// were laid out by position from whatever x registers were tracked, and its
/// result was taken to be x0 whatever it returns. The SDK's headers say both.
/// Each public framework's umbrella header, and one translation unit of the C
/// library and runtime headers, is dumped by clang (`-ast-dump`, text, read a
/// line at a time: the JSON form of one umbrella is over 400 MB), and every
/// external function declaration is kept with its return and each
/// parameter's register bank. A header that does not compile alone is
/// skipped. A declaration without a prototype (`int f()`, whose parameters
/// are unknown, not none) is not kept, and a name declared two different
/// ways is dropped.
@Test func generateSDKCPrototypes() throws {
    guard let output = ProcessInfo.processInfo.environment["SWIFTDC_GENERATE_SDK_C_PROTOTYPES"] else { return }
    let sdk = try #require(CPrototypeDump.sdkPath())
    let frameworks = (try? FileManager.default.contentsOfDirectory(atPath: sdk + "/System/Library/Frameworks")) ?? []
    var units = [CPrototypeDump.libraryUnit]
    units += frameworks.filter { $0.hasSuffix(".framework") }.sorted().map {
        let name = String($0.dropLast(".framework".count))
        return "#import <\(name)/\(name).h>\n"
    }
    var prototypes: [String: String] = [:]
    var conflicting: Set<String> = []
    var compiled = 0
    for unit in units {
        guard let lines = CPrototypeDump.astDump(of: unit) else { continue }
        compiled += 1
        CPrototypeDump.collect(lines, into: &prototypes, conflicting: &conflicting)
    }
    for name in conflicting { prototypes[name] = nil }
    let settings = (try? String(contentsOfFile: sdk + "/SDKSettings.json", encoding: .utf8)) ?? ""
    let sdkVersion = settings.range(of: #""Version":"[^"]*""#, options: .regularExpression)
        .map { "SDK " + settings[$0].dropFirst(#""Version":""#.count).dropLast() } ?? "SDK version unknown"
    let lines = prototypes.keys.sorted().map { "\($0) \(prototypes[$0]!)" }
    let source = """
    // Generated by Tests/SwiftDecompilerCoreTests/SDKCPrototypeGenerator.swift
    // from the macOS \(sdkVersion) headers (\(compiled) of \(units.count) translation units
    // compiled). Do not edit by hand.

    /// The C functions the SDK declares, by name: what each returns (`v`
    /// void, `i` an integer or pointer, `f` float, `d` double, `s` a struct,
    /// union, vector, complex or 128-bit value, `x` a type the generator could
    /// not classify) and the register bank of each parameter in order (`i`,
    /// `f`, `d`, `D<n>` or `F<n>` for a struct of `n` doubles or floats
    /// passed in `n` v registers (an HFA such as CGRect, `D4`), or `s` for
    /// any other struct or a type that could not be classified), with `...`
    /// for a variadic one.
    enum SDKCPrototypes {
        static let table: [String: String] = {
            var table: [String: String] = [:]
            for line in data.split(separator: "\\n") {
                guard let space = line.firstIndex(of: " ") else { continue }
                table[String(line[..<space])] = String(line[line.index(after: space)...])
            }
            return table
        }()

        private static let data = \"\"\"
    \(lines.joined(separator: "\n"))
    \"\"\"
    }

    """
    try source.write(toFile: output, atomically: true, encoding: .utf8)
    print("SDK C prototypes: \(prototypes.count) functions from \(compiled) translation units, \(conflicting.count) declined for conflicting declarations")
}

private enum CPrototypeDump {
    /// The C library and runtime headers no framework umbrella reaches.
    static let libraryHeaders = [
    "stdlib.h", "string.h", "strings.h", "stdio.h", "pthread.h", "malloc/malloc.h", "sqlite3.h",
    "objc/runtime.h", "objc/message.h", "os/log.h", "os/lock.h", "dispatch/dispatch.h", "Block.h",
    "mach/mach.h", "math.h", "unistd.h", "fcntl.h", "sys/stat.h", "xpc/xpc.h", "notify.h", "zlib.h",
    "libproc.h",
    ]

    static var libraryUnit: String { libraryHeaders.map { "#include <\($0)>\n" }.joined() }

    /// The macOS SDK this host's Xcode builds against.
    static func sdkPath() -> String? {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
        process.arguments = ["--sdk", "macosx", "--show-sdk-path"]
        let pipe = Pipe()
        process.standardOutput = pipe
        guard (try? process.run()) != nil else { return nil }
        process.waitUntilExit()
        let path = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return path.isEmpty ? nil : path
    }

    /// The lines of clang's text AST dump that matter here (top-level
    /// typedefs, function declarations and their parameters) for one
    /// translation unit, or nil when it does not compile. The dump is read
    /// in chunks, never whole.
    static func astDump(of unit: String) -> [Substring]? {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
        process.arguments = ["clang", "-x", "objective-c", "-fsyntax-only", "-fno-color-diagnostics",
                             "-Xclang", "-ast-dump", "-"]
        let input = Pipe(), output = Pipe()
        process.standardInput = input
        process.standardOutput = output
        process.standardError = FileHandle.nullDevice
        guard (try? process.run()) != nil else { return nil }
        input.fileHandleForWriting.write(Data(unit.utf8))
        try? input.fileHandleForWriting.close()
        var kept: [Substring] = []
        var pending = Data()
        let handle = output.fileHandleForReading
        func keep(_ line: Data) {
            guard let text = String(data: line, encoding: .utf8) else { return }
            if text.hasPrefix("|-FunctionDecl ") || text.hasPrefix("`-FunctionDecl ")
                || text.hasPrefix("| |-ParmVarDecl ") || text.hasPrefix("| `-ParmVarDecl ")
                || text.hasPrefix("|-TypedefDecl ") || text.hasPrefix("`-TypedefDecl ")
                || text.hasPrefix("|-RecordDecl ") || text.hasPrefix("`-RecordDecl ")
                || text.hasPrefix("| |-FieldDecl ") || text.hasPrefix("| `-FieldDecl ")
                || text.hasPrefix("| |-RecordDecl ") || text.hasPrefix("| `-RecordDecl ")
                || text.hasPrefix("| |-IndirectFieldDecl ") || text.hasPrefix("| `-IndirectFieldDecl ") {
                kept.append(Substring(text))
            } else if text.hasPrefix("|-") || text.hasPrefix("`-") {
                kept.append("|-Other")
            }
        }
        while true {
            let chunk = handle.availableData
            if chunk.isEmpty { break }
            pending.append(chunk)
            while let newline = pending.firstIndex(of: 0x0A) {
                keep(pending[pending.startIndex..<newline])
                pending.removeSubrange(pending.startIndex...newline)
            }
        }
        process.waitUntilExit()
        return process.terminationStatus == 0 ? kept : nil
    }

    /// The name and the two quoted types (`'GLfloat':'float'`) at the end of a
    /// declaration line, the second the first desugared.
    static func declaration(_ line: Substring) -> (name: String, type: String, desugared: String?, rest: String)? {
        guard let open = line.range(of: " '") else { return nil }
        let head = line[..<open.lowerBound]
        guard let nameStart = head.lastIndex(of: " ") else { return nil }
        let name = String(head[head.index(after: nameStart)...])
        var tail = line[open.upperBound...]
        guard let close = tail.firstIndex(of: "'") else { return nil }
        let type = String(tail[..<close])
        tail = tail[tail.index(after: close)...]
        var desugared: String?
        if tail.hasPrefix(":'"), let end = tail.dropFirst(2).firstIndex(of: "'") {
            desugared = String(tail[tail.index(tail.startIndex, offsetBy: 2)..<end])
            tail = tail[tail.index(after: end)...]
        }
        return (name, type, desugared, String(tail))
    }

    static func collect(_ lines: [Substring], into prototypes: inout [String: String], conflicting: inout Set<String>) {
        var typedefs: [String: String] = [:]
        for line in lines where line.hasPrefix("|-TypedefDecl ") || line.hasPrefix("`-TypedefDecl ") {
            // `typedef struct { … } CMTime` prints `'struct CMTime':'CMTime'`:
            // its desugared form is its own name, so the struct is the type.
            if let decl = declaration(line) {
                typedefs[decl.name] = decl.desugared.flatMap { $0 == decl.name ? nil : $0 } ?? decl.type
            }
        }
        func resolve(_ type: String) -> String {
            var type = type
            for _ in 0..<10 {
                for qualifier in ["_Nonnull", "_Nullable", "_Null_unspecified", "__nonnull", "__nullable"] {
                    type = type.replacingOccurrences(of: qualifier, with: "")
                }
                type = type.replacingOccurrences(of: "const ", with: "").replacingOccurrences(of: "volatile ", with: "")
                // clang prints an attribute macro as part of the type
                // (`DISPATCH_RETURNS_RETAINED dispatch_queue_t`): an
                // all-capital word that names no typedef, and is no struct,
                // union or enum tag, is not part of it.
                let words = type.split(separator: " ")
                type = words.indices.filter { index in
                    let word = words[index]
                    let isMacro = word.contains(where: \.isLetter)
                        && word.allSatisfy { $0.isUppercase || $0.isNumber || $0 == "_" }
                        && typedefs[String(word)] == nil
                    let isTag = index > 0 && ["struct", "union", "enum"].contains(words[index - 1])
                    return !isMacro || isTag
                }.map { String(words[$0]) }.joined(separator: " ")
                guard let next = typedefs[type], next != type else { break }
                type = next
            }
            return type
        }
        func bank(_ type: String) -> Character? {
            let type = resolve(type)
            if type == "void" { return "v" }
            if type.contains("*") || type.contains("^") || ["id", "SEL", "Class"].contains(type) || type.hasPrefix("id<") {
                return "i"
            }
            if type == "float" { return "f" }
            if type == "double" || type == "long double" { return "d" }
            if type.hasPrefix("enum ") { return "i" }
            // `__int128` takes two x registers, so it is no single one.
            let words = Set(type.split(separator: " ").map(String.init))
            let integerWords: Set<String> = ["char", "short", "int", "long", "_Bool", "bool", "unsigned", "signed"]
            if !words.isEmpty, words.isSubset(of: integerWords) { return "i" }
            // A struct, union, vector, complex or 128-bit value is in more
            // than one register, or in a vector register whole.
            if type.hasPrefix("struct ") || type.hasPrefix("union ") || type.contains("_Complex")
                || type.contains("vector_size") || type.contains("ext_vector_type") || words.contains("__int128") {
                return "s"
            }
            return nil
        }
        // Each struct definition's field types, nil for one with a member
        // this cannot classify (a nested record, an anonymous member).
        var records: [String: [String]?] = [:]
        var recordIndex = 0
        while recordIndex < lines.count {
            let line = lines[recordIndex]
            recordIndex += 1
            guard line.hasPrefix("|-RecordDecl ") || line.hasPrefix("`-RecordDecl "),
                  line.hasSuffix(" definition"),
                  let structWord = line.range(of: " struct ", options: .backwards)
            else { continue }
            let name = String(line[structWord.upperBound...].dropLast(" definition".count))
            guard !name.isEmpty, !name.contains(" ") else { continue }
            var fields: [String]? = []
            while recordIndex < lines.count, lines[recordIndex].hasPrefix("| ") {
                let child = lines[recordIndex]
                recordIndex += 1
                if child.hasPrefix("| |-FieldDecl ") || child.hasPrefix("| `-FieldDecl "),
                   let field = declaration(child) {
                    fields?.append(field.desugared ?? field.type)
                } else {
                    fields = nil
                }
            }
            records[name] = records[name] == nil ? fields : nil
        }
        /// A homogeneous floating-point aggregate (AAPCS64): one to four
        /// members, after flattening nested structs and arrays, all `float`
        /// or all `double`. Its bank and member count.
        func homogeneousFloats(_ type: String, depth: Int = 0) -> (bank: Character, count: Int)? {
            guard depth < 8 else { return nil }
            let type = resolve(type)
            if type == "float" { return ("F", 1) }
            if type == "double" || type == "long double" { return ("D", 1) }
            if type.hasSuffix("]"), let open = type.lastIndex(of: "["),
               let length = Int(type[type.index(after: open)..<type.index(before: type.endIndex)]), length > 0,
               let element = homogeneousFloats(String(type[..<open]).trimmingCharacters(in: .whitespaces), depth: depth + 1) {
                return (element.bank, element.count * length)
            }
            guard type.hasPrefix("struct "), let fields = records[String(type.dropFirst("struct ".count))] ?? nil,
                  !fields.isEmpty
            else { return nil }
            var bank: Character?
            var count = 0
            for field in fields {
                guard let member = homogeneousFloats(field, depth: depth + 1), bank == nil || bank == member.bank
                else { return nil }
                bank = member.bank
                count += member.count
            }
            guard let bank, (1...4).contains(count) else { return nil }
            return (bank, count)
        }
        var index = 0
        while index < lines.count {
            let line = lines[index]
            index += 1
            guard line.hasPrefix("|-FunctionDecl ") || line.hasPrefix("`-FunctionDecl "),
                  let decl = declaration(line), !decl.rest.contains("static"), !decl.rest.contains("inline")
            else { continue }
            var parameters = ""
            var parsed = true
            while index < lines.count, lines[index].hasPrefix("| |-ParmVarDecl ") || lines[index].hasPrefix("| `-ParmVarDecl ") {
                if let parameter = declaration(lines[index]) {
                    let type = parameter.desugared ?? parameter.type
                    if let scalar = bank(type), scalar != "v", scalar != "s" {
                        parameters.append(scalar)
                    } else if let aggregate = homogeneousFloats(type) {
                        parameters += "\(aggregate.bank)\(aggregate.count)"
                    } else {
                        parameters.append("s")
                    }
                } else {
                    parsed = false
                }
                index += 1
            }
            // `int ()` declares no prototype, so its parameters are unknown;
            // clang prints one that takes nothing as `int (void)`.
            guard parsed, let open = decl.type.firstIndex(of: "("),
                  !parameters.isEmpty || decl.type.contains("(void)")
            else { continue }
            // `void (*(int, void (*)(int)))(int)` is `signal`: the first
            // parenthesis opens the declarator of a function pointer it
            // returns, not its parameters.
            let declarator = decl.type[decl.type.index(after: open)...].first
            let result = declarator == "*" || declarator == "^" ? "i" : bank(String(decl.type[..<open])) ?? "x"
            let variadic = decl.type.contains("...")
            let prototype = "\(result) \(parameters)\(variadic ? "..." : "")"
            if let earlier = prototypes[decl.name], earlier != prototype { conflicting.insert(decl.name) }
            prototypes[decl.name] = prototype
        }
    }
}
