import Foundation
import MachOKit
import ObjCDump
import Testing
@testable import SwiftDecompilerCore

/// Regenerates `Sources/SwiftDecompilerCore/SDKSelectorPrefixes.swift` from
/// this host's dyld shared cache:
///
///     SWIFTDC_GENERATE_SDK_SELECTORS=Sources/SwiftDecompilerCore/SDKSelectorPrefixes.swift \
///         swift test --filter generateSDKSelectorPrefixes
///
/// A send with no signature lays its arguments out one x register each, but
/// its registers follow the declaration the compiler saw, so the classes,
/// categories and protocols of the public frameworks that a public SDK header
/// declares are what matters: a private class's method (`CAContext
/// setLevel:(float)`) is no declaration an app was compiled against. For
/// every selector one of them takes a non-x argument for, the table holds how
/// many leading arguments every one of them passes in an x register.
@Test func generateSDKSelectorPrefixes() throws {
    guard let output = ProcessInfo.processInfo.environment["SWIFTDC_GENERATE_SDK_SELECTORS"] else { return }
    let cache = try #require(FullDyldCache.host)
    let sdk = try #require(sdkPath())
    let declared = publicDeclarations(in: sdk)
    var prefixes: [String: Int] = [:]
    var images = 0
    func record(_ method: ObjCMethodInfo) {
        let selector = method.name
        let colons = selector.filter { $0 == ":" }.count
        // A leading underscore marks a private method, which no public
        // header declares.
        guard colons > 0, !selector.hasPrefix("_") else { return }
        // An encoding that does not parse proves nothing about its layout.
        let prefix = ObjCArgumentABI.parameterTypes(encoding: method.typeEncoding, argumentCount: colons)
            .map { $0.firstIndex { !ObjCArgumentABI.takesOneXRegister($0) } } ?? 0
        guard let prefix else { return }
        prefixes[selector] = min(prefixes[selector] ?? prefix, prefix)
    }
    for image in cache.machOFiles()
    where image.imagePath.hasPrefix("/System/Library/Frameworks/") || image.imagePath == "/usr/lib/libobjc.A.dylib" {
        images += 1
        let snapshot = ObjCMetadataSnapshot.build(in: image, includeProtocols: true)
        for cls in snapshot.classes where declared.classes.contains(cls.name) {
            (cls.classMethods + cls.methods).forEach(record)
        }
        for category in snapshot.categories
        where declared.categories.contains("\(category.className) (\(category.name))") {
            (category.classMethods + category.methods).forEach(record)
        }
        for proto in snapshot.protocols where declared.protocols.contains(proto.name) {
            (proto.classMethods + proto.methods + proto.optionalClassMethods + proto.optionalMethods).forEach(record)
        }
    }
    let version = ProcessInfo.processInfo.operatingSystemVersionString
    let settings = (try? String(contentsOfFile: sdk + "/SDKSettings.json", encoding: .utf8)) ?? ""
    let sdkVersion = settings.range(of: #""Version":"[^"]*""#, options: .regularExpression)
        .map { "SDK " + settings[$0].dropFirst(#""Version":""#.count).dropLast() } ?? "SDK version unknown"
    let lines = prefixes.keys.sorted().map { "\($0) \(prefixes[$0]!)" }
    let source = """
    // Generated by Tests/SwiftDecompilerCoreTests/SDKSelectorPrefixGenerator.swift
    // from the public frameworks of the macOS \(version) shared cache
    // \(cache.header.uuid.uuidString) (\(images) images), keeping the classes,
    // categories and protocols the SDK's headers declare (\(sdkVersion)).
    // Do not edit by hand.

    /// For every Objective-C selector that some public framework's class,
    /// category or protocol takes a struct or floating-point argument for:
    /// how many leading arguments all of them pass one x register each. A
    /// send of it with no signature for its receiver keeps only those.
    enum SDKSelectorPrefixes {
        static let table: [String: Int] = {
            var table: [String: Int] = [:]
            for line in data.split(separator: "\\n") {
                guard let space = line.lastIndex(of: " "), let prefix = Int(line[line.index(after: space)...])
                else { continue }
                table[String(line[..<space])] = prefix
            }
            return table
        }()

        private static let data = \"\"\"
    \(lines.joined(separator: "\n"))
    \"\"\"
    }

    """
    try source.write(toFile: output, atomically: true, encoding: .utf8)
    print("SDK selector prefixes: \(prefixes.count) selectors from \(images) images")
}

/// The macOS SDK this host's Xcode builds against.
private func sdkPath() -> String? {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
    process.arguments = ["--sdk", "macosx", "--show-sdk-path"]
    let pipe = Pipe()
    process.standardOutput = pipe
    guard (try? process.run()) != nil else { return nil }
    process.waitUntilExit()
    let path = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        .trimmingCharacters(in: .whitespacesAndNewlines)
    return path.isEmpty ? nil : path
}

/// The Objective-C classes, categories (`Class (Category)`) and protocols the
/// SDK's framework headers and `usr/include/objc` declare.
private func publicDeclarations(in sdk: String) -> (classes: Set<String>, categories: Set<String>, protocols: Set<String>) {
    var classes = Set<String>(), categories = Set<String>(), protocols = Set<String>()
    let interface = try! NSRegularExpression(pattern: #"@interface\s+([A-Za-z_]\w*)(\s*\(\s*(\w*)\s*\))?"#)
    let proto = try! NSRegularExpression(pattern: #"@protocol\s+([A-Za-z_]\w*)"#)
    let roots = [sdk + "/System/Library/Frameworks", sdk + "/usr/include/objc"]
    for root in roots {
        guard let walker = FileManager.default.enumerator(atPath: root) else { continue }
        for case let relative as String in walker where relative.hasSuffix(".h") {
            guard let text = try? String(contentsOfFile: root + "/" + relative, encoding: .utf8) else { continue }
            let range = NSRange(text.startIndex..., in: text)
            for match in interface.matches(in: text, range: range) {
                guard let name = Range(match.range(at: 1), in: text).map({ String(text[$0]) }) else { continue }
                if match.range(at: 2).location == NSNotFound {
                    classes.insert(name)
                } else if let category = Range(match.range(at: 3), in: text).map({ String(text[$0]) }) {
                    categories.insert("\(name) (\(category))")
                }
            }
            for match in proto.matches(in: text, range: range) {
                if let name = Range(match.range(at: 1), in: text).map({ String(text[$0]) }) { protocols.insert(name) }
            }
        }
    }
    return (classes, categories, protocols)
}
