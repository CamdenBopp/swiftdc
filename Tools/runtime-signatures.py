#!/usr/bin/env python3
"""Generate Sources/SwiftDecompilerCore/SwiftRuntimeSignatures.swift.

Usage: Tools/runtime-signatures.py <swift-runtime-signatures.json> <output>

The input is the table derived from the Swift compiler's checkout, kept on
audit/compiler-grounded at Benchmarks/compiler-grounded/. A function is kept
only when its parameters were read from a declaration or definition, not
derived by hand, and the sources agree on the parameters and the result.
SDKCPrototypes wins for a name the SDK declares, so names in it are left out.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SDK = ROOT / "Sources/SwiftDecompilerCore/SDKCPrototypes.swift"

CONVENTIONS = {"c", "swiftcc", "preserve_most (SwiftDirectRR_CC)"}
RESULTS = {"none": "v", "pointer": "i", "word64": "i", "narrow_fits_w0": "i", "float": "f", "double": "d"}
SIGNED_32 = {"int", "int32_t", "sys_signal_t"}
# Inferences that leave the parameter list as read: where the declaration
# lives, and which registers a two-word result takes. `x` claims nothing about
# that result. The others (x8 results, hand-lowered generics) are dropped.
HARMLESS_INFERENCES = ("declared only by its definition", "two-word aggregate")


def parameter(p):
    bits = p.get("bits")
    if bits is None:
        return "i"
    if bits == 1:
        return "z"
    return "w" if p.get("type") in SIGNED_32 else "u"


def keeps(row, sdk_names):
    disagreements = " ".join(row.get("def_header_disagreement") or [])
    return (
        all(i.startswith(HARMLESS_INFERENCES) for i in row.get("inferred", []))
        and row["calling_convention"].split(" (Swift function")[0] in CONVENTIONS
        and not row["special_registers"]
        and not row.get("variadic_selector_dependent")
        and row["stack_words"] == 0
        and row["v_arg_registers"] == 0
        and "x-arg" not in disagreements
        and "result:" not in disagreements
        and row["name"] not in sdk_names
    )


def main():
    rows = json.load(open(sys.argv[1]))
    sdk_names = set(re.findall(r"^(\S+) \S", SDK.read_text(), re.M))
    lines = []
    for row in sorted(rows, key=lambda r: r["name"]):
        if keeps(row, sdk_names):
            # Two words and a result buffer: `x`, which claims nothing. A
            # MetadataResponse's x0 is the metadata, read as a value today.
            result = RESULTS.get(row["result"]["width_class"], "x")
            lines.append(f'{row["name"]} {result} {"".join(parameter(p) for p in row["params"])}'.rstrip())
    body = "\n".join(lines)
    pathlib.Path(sys.argv[2]).write_text(f'''// Generated by Tools/runtime-signatures.py from the signature table derived
// from the Swift compiler's sources (audit/compiler-grounded,
// Benchmarks/compiler-grounded/swift-runtime-signatures.json). Do not edit by
// hand.

/// The Swift runtime's entry points by name, in the format of `SDKCPrototypes`
/// (the SDK ships no header for them). A function is here only when its
/// declaration or definition was read and agrees with RuntimeFunctions.def.
/// Left out: entry points that take a context in x22, `objc_msgSend` and its
/// kin (the selector decides), generic Swift functions under C names, and
/// anything the SDK declares. A two-word result is `x`, which claims nothing
/// about x0.
enum SwiftRuntimeSignatures {{
    static let table: [String: String] = {{
        var table: [String: String] = [:]
        for line in data.split(separator: "\\n") {{
            guard let space = line.firstIndex(of: " ") else {{ continue }}
            table[String(line[..<space])] = String(line[line.index(after: space)...])
        }}
        return table
    }}()

    private static let data = """
{body}
"""
}}
''')
    print(f"{len(lines)} of {len(rows)} kept")


main()
